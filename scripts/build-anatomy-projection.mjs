#!/usr/bin/env node
/**
 * scripts/build-anatomy-projection.mjs — проекция анатомии для public runtime.
 *
 * INV-06 (r2): candidate-транскрипции не входят в default `./ir`.
 * Default-рантайм строит ТОЛЬКО accepted-модели → ему нужны только их
 * декларации (+ транзитивные mirror-источники). Candidate-корпус уезжает
 * в отдельный артефакт, который потребитель подключает осознанно
 * (`./ir/candidates` → registerCandidates()).
 *
 * Выходы (generated, руками не правятся):
 *   semantics/anatomy.runtime.json    — глифы для accepted-построения
 *   semantics/anatomy.candidates.json — остальные (candidate/authoring)
 * Раздел детерминирован от anatomy.json + catalog.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

const anatomy = read('semantics/anatomy.json');
const catalog = read('semantics/catalog.json');

const runtime = new Set();
for (const icon of Object.values(catalog.icons)) {
  const model = icon.model;
  if (!model) continue;
  const states = Object.values(model.variants).map((v) => v.state);
  if (states.includes('accepted')) runtime.add(model.declaration);
}
// Транзитивно: mirror-глиф строится из источника.
let grew = true;
while (grew) {
  grew = false;
  for (const name of [...runtime]) {
    const glyph = anatomy.glyphs[name];
    if (glyph?.archetype === 'mirror' && glyph.of && !runtime.has(glyph.of)) {
      runtime.add(glyph.of);
      grew = true;
    }
  }
}

const runtimeGlyphs = {};
const candidateGlyphs = {};
for (const [name, glyph] of Object.entries(anatomy.glyphs)) {
  (runtime.has(name) ? runtimeGlyphs : candidateGlyphs)[name] = glyph;
}

const header = (kind) => ({
  version: anatomy.version,
  comment: `GENERATED by scripts/build-anatomy-projection.mjs (${kind}); источник — semantics/anatomy.json. INV-06: runtime = accepted+mirror-sources, candidates = opt-in корпус.`,
});

writeFileSync(
  join(ROOT, 'semantics', 'anatomy.runtime.json'),
  JSON.stringify({ ...header('runtime'), glyphs: runtimeGlyphs }, null, 1) + '\n',
);
writeFileSync(
  join(ROOT, 'semantics', 'anatomy.candidates.json'),
  JSON.stringify({ ...header('candidates'), glyphs: candidateGlyphs }, null, 1) + '\n',
);

const candidateVariants = [];
for (const [icon, entry] of Object.entries(catalog.icons)) {
  for (const [variant, model] of Object.entries(entry.model?.variants ?? {})) {
    if (model.state === 'candidate') candidateVariants.push(`${icon}/${variant}`);
  }
}
candidateVariants.sort();
writeFileSync(
  join(ROOT, 'semantics', 'candidate-variants.json'),
  JSON.stringify({ version: 1, variants: candidateVariants }, null, 1) + '\n',
);
console.log(
  `anatomy-projection: runtime ${Object.keys(runtimeGlyphs).length} глифов, ` +
    `candidates ${Object.keys(candidateGlyphs).length}`,
);
