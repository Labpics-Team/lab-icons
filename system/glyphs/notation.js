/**
 * system/glyphs/notation.js — ЛЕНТА и КЛАСС «СТОПКА».
 *
 * bookmark и bookmarks — не две иконки, а одна лента в одном и двух
 * экземплярах. Второй экземпляр порождает КЛАСС, который в корпусе встречается
 * далеко за пределами закладок (copy, duplicate, files, images, chatbubbles,
 * layers): задний экземпляр сначала ВЫРЕЗАЕТ из себя тень переднего с охранным
 * зазором и только потом передний ложится сверху. Иначе два контура слипаются
 * в кашу на мелком кегле.
 */

import { defineGlyph } from '../registry.js';
import * as S from '../prim/shape.js';
import { cut } from '../core/boolean.js';

/**
 * ЛЕНТА — пятиугольник: прямоугольник, у которого нижняя сторона заменена
 * вырезом-стрелкой. Скругления по-вершинно: верх — корпусное, хвосты —
 * детальное, остриё выреза острое (рука его не скругляет).
 *
 * Вершина хвоста лежит НИЖЕ видимого кончика и даже ниже канвы. Это не ошибка:
 * скругление радиуса r при внутреннем угле φ поднимает кончик над вершиной на
 * r·(1/sin(φ/2) − 1); при φ ≈ 56° и r = 1.87 это 2.1 ед. Задавать вершину —
 * значит задавать конструкцию; задавать кончик — значит задавать результат.
 */
function ribbon(cx, halfW, top, tailVertex, apexY, rTop, rTail, pen, z = 0) {
  const pts = [
    [cx - halfW, top],
    [cx + halfW, top],
    [cx + halfW, tailVertex],
    [cx, apexY],
    [cx - halfW, tailVertex],
  ];
  return S.roundedPolygonRing(pts, [rTop, rTop, rTail, 0, rTail], pen, z);
}

/**
 * Тот же силуэт сплошным. `grow` — смещение кромки по нормали: положительное
 * даёт тень класса «стопка», отрицательное — отступ сплошной массы внутрь.
 * Множитель 1.5 на острие стоит на месте точного 1/sin(φ/2) = 1.414 (плечи
 * выреза идут под 45°) — расхождение 0.09·grow, при grow 0.15 это 0.013 ед.
 * Радиус зажат снизу нулём: при отступе внутрь остриё, у которого радиус и
 * так ноль, ушло бы в отрицательный, а это была бы уже не фигура.
 */
function ribbonSolid(cx, halfW, top, tailVertex, apexY, rTop, rTail, grow, z = 0) {
  const pts = [
    [cx - halfW, top - grow],
    [cx + halfW + grow, top - grow],
    [cx + halfW + grow, tailVertex + grow],
    [cx, apexY + grow * 1.5],
    [cx - halfW - grow, tailVertex + grow],
  ];
  pts[0][0] = cx - halfW - grow;
  const r = (x) => Math.max(0, x);
  return S.roundedPolygon(pts, [r(rTop + grow), r(rTop + grow), r(rTail + grow), r(grow), r(rTail + grow)], z);
}

/** Одиночная лента, Outline (замеры оригинала `bookmark.svg`). */
export const RIBBON = Object.freeze({ halfW: 7.17, top: 1.6, tail: 23.97, apex: 16.37, rTop: 3.21, rTail: 1.87 });
/**
 * Та же лента в Filled. Силуэт УЖЕ и ниже: halfW 7.05 против 7.17, верх 2.02
 * против 1.60. Это не другая иконка — это тот же приём, что у залитого тела
 * календаря: сплошная масса оптически тяжелее рамки и обязана отступить.
 * Скругления при этом те же (3.17 / 1.84 против 3.21 / 1.87 — разброс замера).
 */
export const RIBBON_FILLED = Object.freeze({ halfW: 7.05, top: 2.02, tail: 24.28, apex: 16.39, rTop: 3.17, rTail: 1.84 });
/**
 * Лента в стопке: та же форма, ужатая так, чтобы ПАРА уложилась в живую
 * область. Сдвиг ровно 3 по обеим осям — то есть диагональный, под 45°,
 * на шкале направлений. Зазор выреза 1.0.
 */
export const STACK = Object.freeze({
  halfW: 6.04,
  top: 3.11,
  tail: 21.89,
  apex: 16.26,
  rTop: 2.66,
  rTail: 1.85,
  shift: 3.0,
  clearance: 0.0,
});
/**
 * СТОПКА В ЗАЛИВКЕ — другой закон, чем в контуре, и он вычитан из `d` руки
 * посегментно (`reference/Filled/bookmarks_filled.svg`).
 *
 * 1. ЗАДНЯЯ ЛЕНТА В ЗАЛИВКЕ НЕ ЗАЛИВАЕТСЯ. Её кольцо повторяет контурный
 *    вариант кромка в кромку: внешние 7.44 / 19.56 / верх 1.63, внутренние
 *    9.24 / 17.76 / верх 3.43 — то есть перо ровно 1.80 по всем трём кромкам,
 *    Regular, а не Bold (при 2.4 отклонение вырастает с 1.08% до 6.43%).
 *    Второй субпуть заливки — счётчик — идёт по тем же узлам, что счётчик
 *    контура (10.08 3.43 → 9.46 3.67 → 9.24 4.25 … 17.76 4.25 → 17.52 3.67 →
 *    16.91 3.43), меняясь только там, где в него врезается передняя лента.
 * 2. ЗАЗОРА МЕЖДУ ЛЕНТАМИ НЕТ и здесь: границы счётчика идут прямо по кромкам
 *    передней (y 4.78, x 16.41). Разделителем служит собственный просвет
 *    ЗАДНЕЙ ленты шириной 1.35 = перо-к-перу 3.15 − перо 1.80.
 * 3. ПЕРЕДНЯЯ ЛЕНТА, став сплошной, отступает внутрь на 0.15 — равномерным
 *    смещением кромки, а не переразметкой: левая 4.44→4.59, правая
 *    16.56→16.41, верх 4.63→4.78, и радиусы вершин падают на ту же величину
 *    (2.60→2.44, 2.66→2.47). Одиночная лента подтверждает независимо:
 *    4.86→5.00, 19.17→19.02, радиусы 3.25→3.10 и 3.20→3.07. Семь замеров,
 *    0.13…0.19, медиана 0.15.
 *
 * Подгон площадью на нашей базе садится на 0.13, а не на 0.15, и разница
 * объяснима до сотой: STACK.halfW = 6.04 против замеренных у руки 6.06, то
 * есть база уже на 0.02 уже оригинала. В декларацию идёт ЗАМЕР 0.15; цена
 * честности — 1.08% против 0.65% у подгона.
 */
export const STACK_FILLED = Object.freeze({ inset: 0.15 });

defineGlyph('bookmark', {
  family: 'notation',
  law:
    'лента: пятиугольник с вырезом-стрелкой снизу, рамка пером. Скругление верха — ' +
    'корпусное, хвостов — детальное, остриё выреза острое. Вершина хвоста задаётся ' +
    'конструктивно (ниже канвы), видимый кончик поднимает скругление на r(1/sin(φ/2) − 1)',
  argument:
    'Outline расходится на 1.14%, Filled — на 0.43%; в обоих случаях расхождение это форма ' +
    'хвоста. Рука довела кончик хвоста тремя кривыми Безье переменной кривизны, система ' +
    'ставит одну дугу постоянного радиуса. Разница лежит кольцевой каймой шириной около ' +
    '0.1 ед. по двум хвостам; ни одна деталь не потеряна и не добавлена. Дуга выбрана ' +
    'сознательно: у неё есть центр, то есть ось, вокруг которой хвост будет двигаться при ' +
    'анимации закладки. ПОЧЕМУ РАДИУС СЧЁТЧИКА НА ХВОСТЕ НЕ ОБЪЯВЛЕН ОТДЕЛЬНО: спектр ' +
    'снимает у руки 0.65 и 0.71 против 0.13 у системы, и это выглядит как дефект, но ' +
    'СТЕНКА у руки равна 1.790…1.819 при медиане 1.800 — ровно перу, как и у системы. ' +
    'Постоянная стенка и радиусы, различающиеся не на перо, вместе невозможны: значит ' +
    'спектр меряет не радиус, а сводку составной кривой переменной кривизны. Проверено и ' +
    'то, нет ли у руки общего закона «на счётчике не бывает голого угла» — ОТВЕРГНУТО ' +
    'замером: на счётчиках корпуса 34% углов идеально острые против 29% на внешних ' +
    'контурах, то есть минимального радиуса у руки нет вовсе.',
  outline: (t) =>
    ribbon(t.cx, RIBBON.halfW, RIBBON.top, RIBBON.tail, RIBBON.apex, RIBBON.rTop, RIBBON.rTail, t.stroke.glyph, t.corner.smoothing),
  filled: (t) => {
    const F = RIBBON_FILLED;
    return ribbonSolid(t.cx, F.halfW, F.top, F.tail, F.apex, F.rTop, F.rTail, 0, t.corner.smoothing);
  },
});

defineGlyph('bookmarks', {
  family: 'notation',
  law:
    'та же лента в двух экземплярах со сдвигом 3 по обеим осям (диагональ 45° на шкале ' +
    'направлений); класс «стопка» — задний экземпляр вырезает из себя тень переднего ' +
    'по её силуэту без дополнительного зазора — разделителем служит её собственное перо; передний ложится сверху. Лента ужата так, чтобы пара уложилась в живую область. ' +
    'В заливке заливается ТОЛЬКО передняя лента: задняя остаётся тем же кольцом пером ' +
    'Regular, и разделителем служит уже её собственный счётчик, а не вырезанная тень. ' +
    'Передняя при этом отступает внутрь на 0.15 равномерным смещением кромки',
  outline: (t) => {
    const pen = t.stroke.glyph;
    const z = t.corner.smoothing;
    const s = STACK.shift / 2;
    const back = ribbon(t.cx + s, STACK.halfW, STACK.top - s, STACK.tail - s, STACK.apex - s, STACK.rTop, STACK.rTail, pen, z);
    const front = ribbon(t.cx - s, STACK.halfW, STACK.top + s, STACK.tail + s, STACK.apex + s, STACK.rTop, STACK.rTail, pen, z);
    const shadow = ribbonSolid(
      t.cx - s,
      STACK.halfW,
      STACK.top + s,
      STACK.tail + s,
      STACK.apex + s,
      STACK.rTop,
      STACK.rTail,
      STACK.clearance,
      z,
    );
    return cut(back, shadow).add(front);
  },
  /**
   * Filled: заливается только ПЕРЕДНЯЯ лента; задняя остаётся ровно тем же
   * кольцом, что и в контуре (`t.stroke.base` — Regular, замер по трём кромкам
   * 1.80, см. STACK_FILLED). Вырезать тень не из чего и не нужно: просвет
   * между лентами — это собственный счётчик задней, и он получается сам.
   * Складывать можно прямым `add`: nonzero даёт в счётчике задней +1 (внешняя)
   * −1 (внутренняя) +1 (передняя) = 1, то есть передняя лента заполняет ту
   * часть счётчика, которую перекрывает, и не пробивает в себе дыры.
   * Отрицательный `grow` у передней — то самое смещение кромки внутрь на 0.15.
   */
  filled: (t) => {
    const s = STACK.shift / 2;
    const back = ribbon(
      t.cx + s, STACK.halfW, STACK.top - s, STACK.tail - s, STACK.apex - s, STACK.rTop, STACK.rTail, t.stroke.base,
      t.corner.smoothing,
    );
    const front = ribbonSolid(
      t.cx - s, STACK.halfW, STACK.top + s, STACK.tail + s, STACK.apex + s, STACK.rTop, STACK.rTail,
      -STACK_FILLED.inset, t.corner.smoothing,
    );
    return back.add(front);
  },
});
