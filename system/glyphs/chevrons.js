/**
 * system/glyphs/chevrons.js — семья указателей.
 *
 * Один закон, четыре поворота. Ни одного отдельного рисунка: chevron-back —
 * это chevron-down, повёрнутый на 90°, и ничего больше. Так же и в анимации:
 * поворот — это transform, а не вторая траектория.
 */

import { defineGlyph } from '../registry.js';
import { chevron } from '../parts.js';

/**
 * ШЕВРОН ЗАДАН ЧЕРНИЛАМИ, А НЕ СКЕЛЕТОМ.
 *
 * Это принципиально. Если задавать полуразмах скелета, то при смене пера
 * (Outline 1.8 → Filled 2.4) глиф РАЗДУВАЕТСЯ, и Filled уезжает от оригинала
 * на 39%. Рука так не делает: у неё габарит чернил один и тот же, а скелет
 * поджимается на кап. Замер обоих начертаний:
 *
 *            полуразмах скелета   кап    полуширина чернил
 *   Outline        6.11           0.9          7.01
 *   Filled         5.71           1.2          6.91
 *
 * Одно число (6.96 ± 0.05) вместо двух. Отсюда:
 *     half = INK_HALF − cap,  apex = cy + INK_TIP − cap
 * и Filled получается сам, без второй декларации.
 */
export const CHEVRON_INK_HALF = 6.96;
/**
 * Кончик чернил вершины: 4.68 от центра (замер 16.71 Outline, 16.66 Filled).
 * Значение выбрано МИНИМАКСОМ по восьми вариантам семьи, а не средним: рука
 * развела chevron-down и chevron-up на 0.08 (15.78 против 15.70), одним числом
 * их не накрыть, и правильная цель — не «поточнее к одному», а «одинаково
 * близко ко всем». При 4.68 худший вариант даёт 6.5%, при 4.70 — 8.6%.
 */
export const CHEVRON_INK_TIP = 4.68;

const build = (dir) => (t) => {
  const cap = t.cap.glyph;
  const half = CHEVRON_INK_HALF - cap;
  return chevron(t, {
    dir,
    half,
    open: 45,
    weight: t.stroke.glyph,
    apex: [t.cx, t.cy + CHEVRON_INK_TIP - cap],
  });
};

const LAW =
  'V-знак под 45°, заданный ГАБАРИТОМ ЧЕРНИЛ: полуширина 6.96, кончик вершины ' +
  'на +4.70 от центра. Скелет выводится вычитанием капа, поэтому Filled — то же ' +
  'начертание пером Bold без второй декларации';

const ARG =
  'штриховой глиф: площадная метрика на пере 1.8 даёт 1−IoU ≈ 2δ/(2w−δ), то есть ' +
  '5% уже при смещении контура 0.05 ед. Рука сама этой точности не держит — два ' +
  'терминала ОДНОГО штриха chevron-down стоят на 0.063 друг от друга, плечи идут ' +
  'под 44.75° вместо 45°, а chevron-up и chevron-down у неё разъехались на 0.08. ' +
  'Закон точнее оригинала; мера сходимости здесь — медиана смещения контура.';

for (const dir of ['down', 'up', 'back', 'forward']) {
  defineGlyph(`chevron-${dir}`, { family: 'chevron', law: LAW, argument: ARG, outline: build(dir) });
}
