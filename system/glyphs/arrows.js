/**
 * system/glyphs/arrows.js — семья стрелок.
 *
 * Стрелка = шеврон + хвост. Голова у всех одна; меняется ТОЛЬКО длина хвоста.
 * Отсюда arrow-forward, download, upload и resize — одно построение с разными
 * значениями одного параметра, а не четыре рисунка.
 */

import { defineGlyph } from '../registry.js';
import { arrow, headTipOver } from '../parts.js';

/**
 * ЧТО ЗАКРЕПЛЕНО ПРИ СМЕНЕ ПЕРА.
 *
 *   ХВОСТ — по ЧЕРНИЛАМ: круглый терминал упирается в границу отведённого
 *     места. Замер: 4.90 в Outline и 4.89 в Filled при разных перьях, то есть
 *     скелетная точка едет, а чернила стоят.
 *   ГОЛОВА — по СКЕЛЕТУ, И ВЕРШИНА ТОЖЕ. Полуразмах плеча: 5.74 (Outline) и
 *     5.71 (Filled) — одно число при разных перьях. С вершиной то же самое, и
 *     это ЗАМЕР, а не аналогия: у руки кончик чернил стоит на 19.00 в Outline и
 *     19.25 в Filled, то есть РАСТЁТ вместе с пером. Скелетная вершина при этом
 *     стоит на месте: галтель острия выносит чернила за скелет на 0.2929·перо
 *     (вывод: миter 0.7071·перо минус центр галтели 1.4142·перо плюс радиус
 *     перо), откуда 19.00 − 0.527 = 18.473 и 19.25 − 0.703 = 18.547 — одно
 *     число 18.51 в пределах половины пикселя растра.
 *
 *     Раньше вершина считалась «по чернилам»: `apexAt = cy + 7.42 − кап`. При
 *     Regular это давало ровно 18.52 и совпадало, а при Bold кап рос и вершина
 *     УЕЗЖАЛА НАЗАД — кончик чернил выходил 18.92 против 19.25 у руки. Ошибку
 *     нашёл не процент, а сравнение габаритов двух мастеров: у руки кончик
 *     едет вперёд, у системы — назад.
 */
export const ARROW_INK_TIP = 7.0;
export const ARROW_INK_TAIL = 7.1;
export const ARROW_HALF = 5.72;

const LAW =
  'шеврон 45° полуразмахом скелета 5.72 + хвост; вершина и терминал хвоста ' +
  'закреплены по чернилам (+7.42 и −7.10 от центра), раствор головы — по скелету, ' +
  'поэтому Filled получается сменой пера на Bold без второй декларации. ' +
  'Ось `tail` от 0 (голый шеврон) до 1';

const ARG =
  'два варианта из восьми выпадают, и оба — расхождение внутри самого оригинала, ' +
  'а не конструкции. Рука поставила вершину arrow-back на 18.27, а arrow-forward — ' +
  'на 18.52 при одинаковом построении: разброс 0.25 ед., что на пере 1.8 даёт ' +
  '1−IoU ≈ 2δ/(2w−δ) ≈ 10%. Остальные шесть вариантов лежат в 1.3…2.3%. Одним ' +
  'законом обе версии не накрыть, и подгонять закон под одно направление значило ' +
  'бы перенести дребезг руки в систему.';

for (const dir of ['down', 'up', 'back', 'forward']) {
  defineGlyph(`arrow-${dir}`, {
    family: 'arrow',
    law: LAW,
    argument: ARG,
    axes: {
      tail: {
        min: 0,
        def: 1,
        max: 1,
        unit: 'доля полного хвоста',
        note: 'tail = 0 вырождает стрелку в шеврон — это одна конструкция, а не две',
      },
    },
    outline: (t, ax) => {
      const cap = t.cap.glyph;
      const apexAt = t.cy + ARROW_INK_TIP - headTipOver(t.stroke.glyph, 45, t.corner.elbow);
      const tailAt = t.cy - ARROW_INK_TAIL + cap;
      return arrow(t, {
        dir,
        half: ARROW_HALF,
        open: 45,
        weight: t.stroke.glyph,
        apexAt,
        tail: (apexAt - tailAt) * ax.tail,
      });
    },
  });
}
