export const QUESTION_IN = { c: [0.1, -2.0], r: 2.1, a0: -165, stem: [0.01, 0.91], dot: 4.08 };

/** Угол на окружности, из которого касательная приходит в точку p. */
function tangentAngle(c, r, p) {
  const dx = p[0] - c[0];
  const dy = p[1] - c[1];
  const d = Math.hypot(dx, dy);
  return Math.atan2(dy, dx) - Math.acos(Math.min(1, r / d));
}

const innerQuestion = (t) => {
  const c = [t.cx + QUESTION_IN.c[0], t.cy + QUESTION_IN.c[1]];
  const stem = [t.cx + QUESTION_IN.stem[0], t.cy + QUESTION_IN.stem[1]];
  const a1 = tangentAngle(c, QUESTION_IN.r, stem);
  const spine = new Path().arcFrom(c, QUESTION_IN.r, rad(QUESTION_IN.a0), a1).line(stem);
  return strokePath(spine, PEN(t)).add(S.circle([t.cx, t.cy + QUESTION_IN.dot], CAP(t)));
};

