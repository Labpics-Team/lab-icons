/**
 * system/glyphs/enclosed.js — НАКЛАДНОЙ КЛАСС «в круге».
 *
 * Двадцать имён — это не двадцать иконок, а ОДИН класс и двадцать начинок.
 * Класс объявлен один раз в `enclose()`; всё, что отличает alert-circle от
 * plus-circle, — функция, строящая внутренний глиф.
 *
 * ТРИ ЗАКОНА КЛАССА (сняты с корпуса, см. замеры у каждой константы).
 *
 * 1. КОНТЕЙНЕР — keyline-кольцо. Внешний радиус = t.keyR (11 = живая область
 *    пополам), перо = stroke.ring (1.5), внутренняя кромка = 11 − 1.5 = 9.5.
 *    Рука: `M12 1A11 11…M12 2.5A9.5 9.5…` во всех восемнадцати штриховых
 *    членах семьи — ровно keyR и ровно ring, без единого исключения.
 *    Два члена (arrow-redo/undo) несут кольцо пером base (1.8): их кромка
 *    9.2 = 11 − 1.8. Это не другой закон, это другой ВЕС того же закона.
 *
 * 2. ПЕРО НАЧИНКИ — stroke.containerGlyph (2.0), а НЕ stroke.glyph.
 *    Проверено по всем двадцати: каждая дуга терминала внутри круга — `a1 1`,
 *    то есть кап ровно 1.0 = 2.0/2. И, что важнее, в Filled перо НЕ меняется:
 *    там те же `a1 1`. Контейнер уже несёт всю разницу начертаний, начинке
 *    жирнеть некуда — потому здесь и стоит служебный вес контейнера, а ось
 *    fill на начинку не действует.
 *
 * 3. FILLED — тот же диск МИНУС та же начинка негативом. Одна конструкция,
 *    два прочтения: `cut(disc, glyph)` вместо `ring.add(glyph)`.
 *
 * ВНУТРЕННИЙ KEYLINE — половина внешнего. Чернила начинки вписаны в
 * окружность радиуса keyR/2 = 5.5. Прямые замеры радиуса чернил от центра:
 *   plus 5.50, minus 5.48 — попадание в keyR/2 с точностью 0.02;
 *   close 5.26, checkmark 5.25, play 5.21, стрелки 5.13…5.17,
 *   question 5.11, alert 5.10, шевроны 4.96…5.11, pause 4.95.
 * То есть осевые знаки стоят на половинном keyline точно, а диагональные и
 * составные рука оптически поджала на 0.2…0.5 — тот же приём, что и в
 * свободной семье (там close тоже мельче plus). Класс объявляет keyR/2, а
 * поджатие каждого силуэта — его собственный именованный габарит.
 */

import { defineGlyph } from '../registry.js';
import { Path } from '../core/path.js';
import { orientCW } from '../core/boolean.js';
import { rad } from '../core/num.js';
import * as S from '../prim/shape.js';
import { chevron, arrow, strokePath, strokePolyline, strokeSegment, cut } from '../parts.js';

// ── ОПОРНЫЕ ВЕЛИЧИНЫ КЛАССА (все — выводы из токенов) ─────────────────────

/** Центр канвы. */
const C = (t) => [t.cx, t.cy];
/** Перо начинки: служебный вес глифа-в-контейнере, к оси fill не чувствителен. */
const PEN = (t) => t.stroke.containerGlyph;
/** Терминал начинки = перо/2. */
const CAP = (t) => t.cap.containerGlyph;
/** ВНУТРЕННИЙ KEYLINE ПО ЧЕРНИЛАМ: половина внешнего. */
const INK = (t) => t.keyR / 2;
/** Тот же keyline по СКЕЛЕТУ: чернила минус кап. */
const KEY = (t) => INK(t) - CAP(t);

/**
 * Вырезать начинку из диска. `cut` принимает регион одним куском, а начинка
 * бывает из нескольких подпутей (точка + штрих у alert, две пластины у pause),
 * поэтому режем подпуть за подпутём: иначе в дырку уйдёт только первый.
 */
function holes(disc, glyph) {
  let p = disc;
  for (const sub of glyph.clone().subs) {
    if (!sub.segs.length) continue;
    p = cut(p, new Path([sub]));
  }
  return p;
}

const CLASS_LAW =
  'кольцо keyline (R = keyR, перо stroke.ring, кромка keyR − ring) + начинка пером ' +
  'stroke.containerGlyph, вписанная в половинный keyline keyR/2; Filled — тот же диск минус ' +
  'та же начинка негативом (nonzero, развёрнутый подпуть)';

/**
 * Объявить члена класса. `inner` строит начинку в полной канве.
 * @param {(t:object)=>Path} inner
 */
function declare(name, law, inner, o = {}) {
  const ringWeight = o.ring ?? ((t) => t.stroke.ring);
  defineGlyph(name, {
    family: 'enclosed',
    law: `${law}. Класс: ${CLASS_LAW}`,
    ...(o.argument ? { argument: o.argument } : {}),
    outline: (t) => S.ring(C(t), t.keyR, ringWeight(t)).add(inner(t)),
    filled: (t) => holes(S.circle(C(t), t.keyR), inner(t)),
  });
}

// ── ОСЕВЫЕ ЗНАКИ: minus, plus, close ──────────────────────────────────────
//
// Свободные собратья стоят на осевом keyline 6 (geometric.AXIAL). В круге тот
// же скелет садится на половинный keyline: терминал = keyR/2 − кап = 4.5.
// Замеры руки: minus 4.43, plus 4.44 по обеим осям, close 4.32 (среднее по
// четырём плечам). Закон дороже подгона на 0.07…0.18 ед. и ни на одно число
// не опирается, кроме keyR.

const innerMinus = (t) => strokeSegment([t.cx - KEY(t), t.cy], [t.cx + KEY(t), t.cy], PEN(t));
const innerPlus = (t) => S.cross(C(t), INK(t), CAP(t), CAP(t), 0);
const innerClose = (t) => S.cross(C(t), INK(t), CAP(t), CAP(t), 0, Math.PI / 4);

declare(
  'minus-circle',
  'штрих по горизонтали, терминалы на половинном keyline (keyR/2 − кап = 4.5); рука 4.43',
  innerMinus,
);
declare(
  'plus-circle',
  'крест: плечи до половинного keyline по чернилам (keyR/2 = 5.5), внешний радиус вершины = кап ⟹ ' +
    'терминал выводится смыканием двух скруглений, внутренние вершины острые; рука 5.50',
  innerPlus,
);
declare(
  'close-circle',
  'тот же крест, повёрнутый на 45°: X и + внутри круга — одна форма в двух положениях',
  innerClose,
);

// ── ШЕВРОНЫ ───────────────────────────────────────────────────────────────

/**
 * ПОЛУРАЗМАХ ШЕВРОНА В КОНТЕЙНЕРЕ = 3.93 (канва 24).
 * Замеры по четырём направлениям (полурасстояние между центрами терминалов):
 *   down 3.925, back 3.930, forward 3.938, up 3.940.
 * Из токенов не выводится: свободный шеврон держит 6.1, а половинный keyline
 * дал бы 4.19 — рука поджала указатель ещё на 0.26 сверх общего ужатия
 * (чернила шеврона 5.09 против 5.5 у осевых знаков).
 */
export const CHEVRON_HALF_IN = 3.93;

/**
 * ПОСАДКА ШЕВРОНА — не координата вершины, а ПОЛОЖЕНИЕ ТЕРМИНАЛОВ: они стоят
 * на расстоянии ровно в кап от поперечной оси канвы, то есть кромка терминала
 * КАСАЕТСЯ этой оси. Замеры смещения терминалов от оси (в сторону, обратную
 * указанию): down 1.28, back 0.97, forward 0.99, up 0.69 — среднее 0.98 при
 * капе 1.00. Отсюда вершина = полуразмах − кап; закон снимает лишнее число.
 *
 * Свободный шеврон посажен иначе (через локоть: внутренняя кромка касается
 * окружности channel в центре канвы). Внутри контейнера тот же локоть дал бы
 * зазор 1.086 — величину без имени; поперечная ось даёт кап, величину с именем.
 */
const chevronApexIn = (t) => CHEVRON_HALF_IN - CAP(t);

const innerChevron = (dir) => (t) =>
  chevron(t, {
    dir,
    half: CHEVRON_HALF_IN,
    open: 45,
    weight: PEN(t),
    apex: [t.cx, t.cy + chevronApexIn(t)],
  });

const CHEVRON_ARG =
  'штриховая начинка на пере 2.0: 1−IoU ≈ 2δ/(2w−δ), то есть 0.06 ед. смещения стоят 3% ' +
  'ПЛОЩАДИ НАЧИНКИ. Расхождение здесь мерит разброс самой руки: четыре шеврона одного ' +
  'построения посажены на 1.28 / 0.97 / 0.99 / 0.69 от поперечной оси — размах 0.59 ед. ' +
  'при пере 2.0, вчетверо больше всего допуска метрики. Закон ставит их на кап (1.00) — ' +
  'ближе к трём из четырёх, чем они стоят друг к другу. Второе пятно — наружный локоть: ' +
  'система даёт круглый сустав радиусом кап (вылет 1.414 за вершину), рука срезает его ' +
  'дугой R2 с ζ-сглаживанием и выносит 0.59. Кольцо (78% чернил) совпадает точно.';

for (const dir of ['down', 'up', 'back', 'forward']) {
  declare(
    `chevron-${dir}-circle`,
    'V-знак пером контейнера: плечи 45°, полуразмах 3.93, терминалы кромкой касаются ' +
      'поперечной оси канвы (отстоят от неё на кап) — отсюда вершина = полуразмах − кап',
    innerChevron(dir),
    { argument: CHEVRON_ARG },
  );
}

// ── СТРЕЛКИ ───────────────────────────────────────────────────────────────

/**
 * СТРЕЛКА В КОНТЕЙНЕРЕ, ГАБАРИТЫ ЧЕРНИЛ от центра канвы.
 *   кончик вершины  = INK = keyR/2 = 5.50   (рука: 5.505 / 5.508 / 5.468 — закон)
 *   терминал хвоста = 5.00                  (рука: 5.00 / 5.00 / 5.00 — три замера в ноль)
 *   полувысота головы = 5.17                (рука: 5.163 / 5.165 / 5.168)
 * Кончик выводится из половинного keyline; хвост и полувысота — нет, потому
 * объявлены. Скелет получается вычитанием капа, как и в свободной семье.
 */
export const ARROW_INK_TAIL_IN = 5.0;
export const ARROW_INK_HALF_IN = 5.17;

const innerArrow = (dir) => (t) => {
  const cap = CAP(t);
  const apexAt = t.cy + INK(t) - cap;
  const tailAt = t.cy - (ARROW_INK_TAIL_IN - cap);
  return arrow(t, {
    dir,
    half: ARROW_INK_HALF_IN - cap,
    open: 45,
    weight: PEN(t),
    apexAt,
    tail: apexAt - tailAt,
  });
};

for (const dir of ['down', 'up', 'back', 'forward']) {
  declare(
    `arrow-${dir}-circle`,
    'шеврон 45° + хвост по оси; кончик чернил на половинном keyline (keyR/2), ' +
      'терминал хвоста 5.00, полувысота головы 5.17 — скелет = чернила минус кап',
    innerArrow(dir),
  );
}

// ── ЧЕК И ДВОЙНОЙ ЧЕК ─────────────────────────────────────────────────────

/**
 * СКЕЛЕТ ЧЕКА В КОНТЕЙНЕРЕ — ломаная из трёх точек, в долях внутреннего
 * keyline KEY (= keyR/2 − кап = 4.5), от центра канвы.
 * Прямые замеры по корпусу (канва 24, ось штриха восстановлена как середина
 * между кромками пера):
 *   короткий терминал (8.355, 12.770) → (−0.810, +0.171)·KEY
 *   локоть            (10.381, 15.679) → (−0.360, +0.818)·KEY
 *   длинный терминал  (14.735,  8.685) → (+0.608, −0.737)·KEY
 * Плечи идут под 55.4° и 58.1° к горизонтали — вне шкалы направлений, то есть
 * это намеренная диагональ рисунка, а не снап. Длинный терминал сидит на
 * радиусе 4.30 ≈ KEY: чек вписан в тот же половинный keyline.
 */
export const CHECK_IN = [
  [-0.81, 0.171],
  [-0.36, 0.818],
  [0.608, -0.737],
];

const checkPts = (t, dx = 0) => CHECK_IN.map(([u, v]) => [t.cx + u * KEY(t) + dx, t.cy + v * KEY(t)]);

const innerCheck = (t) => strokePolyline(checkPts(t), PEN(t));

/**
 * ДВОЙНОЙ ЧЕК: шаг между знаками 4.32 = 2·2.16, вся пара сдвинута вправо на
 * 0.12 относительно одиночного чека. Замеры (канва 24): первый чек стоит на
 * −2.04 (терминалы 12.705 против 14.735 и 6.295 против 8.355), второй штрих —
 * на +2.28 (терминал 17.010 против 14.735); полусумма 2.16, полуразность 0.12.
 * Шаг НЕ масштабируется вместе со знаком: в свободной семье он тот же
 * (−2.20 / +2.29) при пере 1.8.
 *
 * Второй штрих короче плеча на 0.39 у локтевого конца: локтя у него нет, а
 * значит нет и суставного вылета — штрих обрывается терминалом.
 */
export const CHECKMARKS_STEP = 2.16;
export const CHECKMARKS_BIAS = 0.12;
export const CHECKMARKS_TRIM = 0.39;

const innerChecks = (t) => {
  const w = PEN(t);
  const p = strokePolyline(checkPts(t, CHECKMARKS_BIAS - CHECKMARKS_STEP), w);
  const far = checkPts(t, CHECKMARKS_BIAS + CHECKMARKS_STEP);
  const [, V, B] = far;
  const k = 1 - CHECKMARKS_TRIM / Math.hypot(V[0] - B[0], V[1] - B[1]);
  return p.add(strokeSegment(B, [B[0] + (V[0] - B[0]) * k, B[1] + (V[1] - B[1]) * k], w));
};

// Единственное известное расхождение чека — наружный локоть: система ставит
// круглый сустав радиусом кап (вылет 1.0 за ось), рука срезает его дугой R1.5
// со сглаживанием и выносит 0.61. Пятно 1.5×1.5 ед. внизу знака, 0.3% площади.

declare(
  'checkmark-circle',
  'ломаная из трёх точек пером контейнера; длинный терминал на половинном keyline, ' +
    'плечи под 55.4°/58.1° — намеренная диагональ, скелет объявлен долями keyline',
  innerCheck,
);
declare(
  'checkmarks-circle',
  'тот же чек, сдвинутый на −шаг, плюс одно длинное плечо того же чека, сдвинутое на +шаг: ' +
    'вторая галочка — не второй рисунок, а то же плечо',
  innerChecks,
);

// ── ЛАТИНСКАЯ «i» И ВОСКЛИЦАТЕЛЬНЫЙ ЗНАК ──────────────────────────────────

/**
 * РАДИУС МЕЛКОЙ ДЕТАЛИ В КОНТЕЙНЕРЕ = 1.25 (канва 24).
 * Два независимых замера: точка над «i» (`a1.25 1.25` в info-circle обоих
 * начертаний) и полуширина верха восклицательного знака (10.75…13.25 = 2.50).
 * Крупнее капа пера (1.0) — точка обязана читаться отдельно от штриха.
 */
export const DETAIL_R = 1.25;

/**
 * СКЕЛЕТ «i» В КОНТЕЙНЕРЕ (канва 24, от центра). Замеры:
 *   верхняя засечка (10.18, 11.07) → (12.12, 11.07)   длина 1.94
 *   ножка           (12.12, 11.07) → (12.12, 16.41)   длина 5.34
 *   нижняя полка    ( 9.90, 16.41) → (14.20, 16.41)   полуширина 2.15
 *   точка           (12.00,  7.93) r = DETAIL_R
 * Свободный `info` держит те же пропорции при пере 1.8: 2.73 / 7.52 / 3.00 —
 * отношение 0.711 / 0.710 / 0.717, то есть контейнер ужимает «i» одним
 * коэффициентом 0.71, а радиус точки оставляет как есть (1.25 в обоих).
 */
export const INFO_IN = { serif: 1.94, top: -0.93, foot: 4.41, half: 2.15, dot: -4.07 };

const innerInfo = (t) => {
  const w = PEN(t);
  const yTop = t.cy + INFO_IN.top;
  const yFoot = t.cy + INFO_IN.foot;
  return strokePolyline([[t.cx - INFO_IN.serif, yTop], [t.cx, yTop], [t.cx, yFoot]], w)
    .add(strokeSegment([t.cx - INFO_IN.half, yFoot], [t.cx + INFO_IN.half, yFoot], w))
    .add(S.circle([t.cx, t.cy + INFO_IN.dot], DETAIL_R));
};

declare(
  'info-circle',
  'латинская «i» пером контейнера: засечка + ножка одной ломаной, нижняя полка отдельным ' +
    'штрихом, точка радиусом мелкой детали; пропорции свободного info, ужатые в 0.71',
  innerInfo,
);

/**
 * ВОСКЛИЦАТЕЛЬНЫЙ ЗНАК В КОНТЕЙНЕРЕ — сужающаяся книзу пластина + точка.
 * Замеры (канва 24): верх y = 7.00 полушириной 1.25 (= DETAIL_R), низ
 * y = 13.90 полушириной 0.98, скругления 0.9 сверху и 0.6 снизу,
 * точка (12.00, 16.10) радиусом 1.00 = кап пера контейнера.
 * Свободный `alert` устроен так же (2.00 → 1.63, высота 9.8): в контейнере
 * высота 6.90 — те же 0.70 общего ужатия.
 */
export const ALERT_IN = { top: -5.0, bottom: 1.9, half: 0.98, rTop: 0.9, rBottom: 0.6, dot: 4.1 };

const innerAlert = (t) => {
  const yT = t.cy + ALERT_IN.top;
  const yB = t.cy + ALERT_IN.bottom;
  return S.roundedPolygon(
    [
      [t.cx - DETAIL_R, yT],
      [t.cx + DETAIL_R, yT],
      [t.cx + ALERT_IN.half, yB],
      [t.cx - ALERT_IN.half, yB],
    ],
    [ALERT_IN.rTop, ALERT_IN.rTop, ALERT_IN.rBottom, ALERT_IN.rBottom],
    t.corner.smoothing,
  ).add(S.circle([t.cx, t.cy + ALERT_IN.dot], CAP(t)));
};

declare(
  'alert-circle',
  'пластина, сужающаяся книзу (полуширина DETAIL_R → 0.98), плюс точка радиусом кап на 4.10 ' +
    'ниже центра: восклицательный знак — не штрих, а сужающийся силуэт',
  innerAlert,
);

// ── ПАУЗА ─────────────────────────────────────────────────────────────────

/**
 * ПЛАСТИНА ПАУЗЫ (канва 24). Замеры по обеим пластинам и обоим начертаниям:
 *   ширина 3.31 (8.20…11.51 и 12.49…15.81), высота 7.26 (8.40…15.66),
 *   скругление 0.80 (`a.8 .8` во всех четырёх углах каждой пластины).
 * Канал между пластинами 0.98 — это кап пера контейнера, потому не объявлен,
 * а выведен: негатив между пластинами читается как терминал.
 */
export const PAUSE_IN = { w: 3.31, h: 7.26, r: 0.8 };

const innerPause = (t) => {
  const dx = (PAUSE_IN.w + CAP(t)) / 2;
  const bar = (x) => S.roundedRect(x, t.cy, PAUSE_IN.w, PAUSE_IN.h, PAUSE_IN.r, t.corner.smoothing);
  return bar(t.cx - dx).add(bar(t.cx + dx));
};

declare(
  'pause-circle',
  'две сплошные пластины 3.31×7.26 со скруглением 0.80, канал между ними = кап пера контейнера',
  innerPause,
);

// ── ПУСК ──────────────────────────────────────────────────────────────────

/**
 * ТРЕУГОЛЬНИК ПУСКА (канва 24, от центра). Замеры по восстановленным острым
 * вершинам (прямые продолжены до пересечения):
 *   вершина (17.97, 12.00) → +5.97 по оси
 *   основание x = 8.68 → −3.32, полувысота 5.88 (6.12…17.88)
 *   скругления: вершина 1.50, основание 1.15 (обе восстановлены по вылету
 *   чернил: 16.71 и 7.30 при ζ = corner.smoothing)
 * Треугольник вписан в окружность радиуса 6.50 с центром (11.465, 12) —
 * равнобедренный, но НЕ правильный: правильный дал бы основание на 8.215.
 */
