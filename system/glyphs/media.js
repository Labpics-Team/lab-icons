/**
 * КЛИН С ДУГОВЫМ ФЛАНКОМ: две галтели радиуса r на оси A→B, с одной стороны
 * прямая касательная (при равных радиусах она параллельна оси), с другой —
 * дуга радиуса Rf, касающаяся обеих галтелей ИЗНУТРИ.
 *
 * Почему именно эта фигура эквидистантна. Наращивание на h увеличивает r и Rf
 * на h и НЕ ДВИГАЕТ ни A, ни B, ни центр фланка: условие касания
 * |Cf − A| = Rf − r сохраняется само. Значит внешняя кромка и счётчик —
 * одна и та же конструкция при r ± перо/2, и стенка выходит ровной по всей
 * длине без единой подгонки. Выпуклая оболочка двух кругов этим свойством
 * тоже обладает, но даёт ПРЯМОЙ фланк, а рука ведёт его дугой.
 *
 * `inward` — точка, в сторону которой смотрит прямая сторона (центр канвы):
 * дуга выгибается ОТ своего центра, поэтому центр фланка берётся тот из двух
 * решений, что лежит на внутренней стороне оси.
 */
function arcWedge(A, B, r, Rf, inward) {
  const L = v2.dist(A, B);
  const u = v2.mul(v2.sub(B, A), 1 / L);
  const M = v2.mul(v2.add(A, B), 0.5);
  let n = [-u[1], u[0]];
  // n смотрит на сторону ФЛАНКА — прочь от inward
  if (v2.dot(n, v2.sub(inward, M)) > 0) n = v2.mul(n, -1);
  const d = Math.sqrt(Math.max(0, (Rf - r) ** 2 - (L / 2) ** 2));
  const Cf = v2.mad(M, n, -d);
  const ang = (c, p) => Math.atan2(p[1] - c[1], p[0] - c[0]);
  const PA = v2.mad(Cf, v2.norm(v2.sub(A, Cf)), Rf);
  const PB = v2.mad(Cf, v2.norm(v2.sub(B, Cf)), Rf);
  const QA = v2.mad(A, n, -r);
  const QB = v2.mad(B, n, -r);
  const sweep = (c, p, q, dir) => {
    let a0 = ang(c, p);
    let a1 = ang(c, q);
    if (dir > 0) while (a1 < a0) a1 += 2 * Math.PI;
    else while (a1 > a0) a1 -= 2 * Math.PI;
    return [a0, a1];
  };
  // Обход берётся ПО ЧАСОВОЙ (в канве y вниз это положительная площадь) — той
  // же намоткой, что у обода. Разная намотка слоёв в одном пути при nonzero
  // означала бы, что в перекрытии чернила гаснут.
  // Все три дуги идут одним знаком: касания непрерывны, и сумма их поворотов
  // обязана дать ровно 360° (замер построения: 106.9 + 146.2 + 106.9).
  const dir = v2.cross(u, n) < 0 ? 1 : -1;

  // ВЫРОЖДЕНИЕ ГАЛТЕЛИ. Когда r < 0 (эквидистанта внутрь ушла за ось —
  // именно это и происходит со счётчиком: 1.7 − 1.8 = −0.1), дуги галтелей в
  // эквидистанте не существует: две стороны пересекаются, и честный офсет —
  // это ОБРЕЗКА по их пересечению, а не дуга отрицательного радиуса. Тогда
  // фигура вырождается в линзу: хорда (сдвинутая прямая) плюс большая дуга
  // фланка. Рука пишет ровно линзу — у её счётчика оба конца УЗЛЫ:
  // (18.84, 13.53) и (14.74, 20.73), а не скругления.
  if (r <= TEPS) {
    const e = v2.sub(QA, Cf);
    const b = v2.dot(e, u);
    const disc = b * b - v2.dot(e, e) + Rf * Rf;
    if (disc <= 0) return new Path();
    const q = Math.sqrt(disc);
    const Ka = v2.mad(QA, u, -b - q);
    const Kb = v2.mad(QA, u, -b + q);
    const [k0, k1] = sweep(Cf, Ka, Kb, dir);
    return new Path().move(Kb).line(Ka).arc(Cf, Rf, k0, k1).close();
  }

  const p = new Path().move(QB).line(QA);
  const [a0, a1] = sweep(A, QA, PA, dir);
  p.arc(A, r, a0, a1);
  const [f0, f1] = sweep(Cf, PA, PB, dir);
  p.arc(Cf, Rf, f0, f1);
  const [b0, b1] = sweep(B, PB, QB, dir);
  p.arc(B, r, b0, b1);
  return p.close();
}

/** Центры оконечностей правой чашки: низ на кромке обода, нос — по оси. */
function cupAxis(t) {
  const R = t.keyR - t.stroke.base; // внутренняя кромка обода, 9.2
  const B = v2.polar([t.cx, t.cy], R, rad(CUP.pivotDeg));
  const A = v2.mad(B, [Math.cos(rad(CUP.axisDeg)), -Math.sin(rad(CUP.axisDeg))], CUP.axis);
  return [A, B];
}

/**
 * Чашка. weight = 0 — сплошной силуэт (Filled), иначе штрих: тот же клин при
 * радиусах, ужатых на перо (закон rInner = rOuter − перо), счётчик развёрнут.
 *
 * Галтель 1.7 УЖЕ пера 1.8, поэтому счётчик вырождается в линзу с узлами на
 * концах — см. arcWedge.
 */
function cupShape(t, weight) {
  const [A, B] = cupAxis(t);
  const c = [t.cx, t.cy];
  const outer = arcWedge(A, B, CUP.end, CUP.flank, c);
  if (!weight) return outer;
  return outer.add(arcWedge(A, B, CUP.end - weight, CUP.flank - weight, c).reverse());
}

function headphone(t, weight) {
  const p = band([t.cx, t.cy], t.keyR - t.cap.base, rad(BAND_END_DEG), rad(540 - BAND_END_DEG), t.stroke.base, 'butt');
  p.add(cupShape(t, weight));
  // Зеркало меняет ЗНАК ОБХОДА (det < 0). Обод не зеркалится, поэтому левая
  // чашка приходит в общий путь с обратной намоткой, и в месте, где она
  // накрывает обод, nonzero даёт +1 − 1 = 0 — чернила гаснут. Разворот
  // возвращает обход, и слои складываются, а не вычитаются.
  p.add(cupShape(t, weight).mirrorX(t.cx));
  return p;
}

